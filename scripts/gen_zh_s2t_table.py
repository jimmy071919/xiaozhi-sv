#!/usr/bin/env python3
"""Generate main/display/zh_s2t_table.inc from OpenCC dictionaries.

Produces Simplified -> Traditional (Taiwan) tables used to convert server text
for display:
  - a character table (STCharacters + TWVariants), BMP only
  - 2- and 3-character phrase tables for phrases whose character-level
    conversion would be wrong (from STPhrases), limited to characters in the
    font charset so the table stays small
  - Taiwan vocabulary replacements applied to the Traditional result
    (TWPhrasesIT/Name/Other, e.g. 軟件 -> 軟體), like OpenCC s2twp

Usage:
  python3 scripts/gen_zh_s2t_table.py <opencc-dictionary-dir> <charset.json> [output]

<opencc-dictionary-dir> must contain STCharacters.txt, STPhrases.txt,
TWVariants.txt and TWPhrases{IT,Name,Other}.txt from https://github.com/BYVoid/OpenCC/tree/master/data/dictionary
"""
import json
import sys
from pathlib import Path


def load_dict(path):
    result = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        key, values = line.split("\t", 1)
        result[key] = values.split(" ")[0]
    return result


def is_bmp(text):
    return all(ord(c) < 0x10000 for c in text)


def hex_list(text):
    return ", ".join(f"0x{ord(c):04X}" for c in text)


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 1
    opencc_dir = Path(sys.argv[1])
    charset = set(json.loads(Path(sys.argv[2]).read_text())["codepoints"])
    output = Path(sys.argv[3] if len(sys.argv) > 3 else
                  Path(__file__).resolve().parent.parent / "main/display/zh_s2t_table.inc")

    characters = load_dict(opencc_dir / "STCharacters.txt")
    variants = load_dict(opencc_dir / "TWVariants.txt")
    phrases = load_dict(opencc_dir / "STPhrases.txt")

    def to_tw(text):
        return "".join(variants.get(c, c) for c in text)

    char_map = {}
    for simp, trad in characters.items():
        trad = to_tw(trad)
        if len(simp) == 1 and len(trad) == 1 and simp != trad and is_bmp(simp + trad):
            char_map[simp] = trad

    def convert_chars(text):
        return "".join(char_map.get(c, c) for c in text)

    phrase_maps = {2: {}, 3: {}}
    for simp, trad in phrases.items():
        trad = to_tw(trad)
        if len(simp) not in phrase_maps or len(trad) != len(simp) or not is_bmp(simp + trad):
            continue
        if not all(ord(c) in charset for c in simp):
            continue
        if convert_chars(simp) != trad:
            phrase_maps[len(simp)][simp] = trad

    lines = [
        "// Auto-generated by scripts/gen_zh_s2t_table.py from OpenCC "
        "(Apache-2.0). Do not edit.",
        "// clang-format off",
        "",
        f"static const ZhCharPair kZhS2TChars[{len(char_map)}] = {{",
    ]
    for simp in sorted(char_map, key=ord):
        lines.append(f"    {{{hex_list(simp)}, {hex_list(char_map[simp])}}},")
    lines.append("};")
    for length, table in phrase_maps.items():
        lines.append("")
        lines.append(f"static const ZhPhrase{length} kZhS2TPhrases{length}[{len(table)}] = {{")
        for simp in sorted(table, key=lambda s: [ord(c) for c in s]):
            lines.append(f"    {{{{{hex_list(simp)}}}, {{{hex_list(table[simp])}}}}},")
        lines.append("};")

    tw_phrases = {}
    for name in ("TWPhrasesIT.txt", "TWPhrasesName.txt", "TWPhrasesOther.txt"):
        tw_phrases.update(load_dict(opencc_dir / name))
    tw_phrases = {k: v for k, v in tw_phrases.items() if k != v}
    lines.append("")
    lines.append("// Longest first so longer vocabulary wins over its prefixes")
    lines.append(f"static const ZhVocabulary kZhTwVocabulary[{len(tw_phrases)}] = {{")
    for trad in sorted(tw_phrases, key=lambda s: (-len(s.encode()), s)):
        lines.append(f'    {{"{trad}", "{tw_phrases[trad]}"}},')
    lines.append("};")
    lines.append("")
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"{output}: {len(char_map)} chars, {len(phrase_maps[2])} 2-char phrases, "
          f"{len(phrase_maps[3])} 3-char phrases, {len(tw_phrases)} vocabulary entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
